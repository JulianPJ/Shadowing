'use client';
import { AUTO_GENERATED_SUFFIX, autoGeneratedCaptions } from '../caption-labels';
import { createImportedLesson } from '../import-lesson';
import type { ResolvedMedia } from '../types';
import { bridgeRequest, bridgeVersion } from './bridge';

/**
 * YouTube captions read from the learner's own connection through Hibiki Bridge, for when YouTube
 * limits Hibiki's servers. The browser-sourced transcript stays a lesson on this device and never
 * enters the shared transcript cache, like imported or page subtitles.
 */
export const BRIDGE_CAPTIONS = 'YouTube captions via Hibiki Bridge';

/** Hibiki Bridge 0.3.0 added the restricted youtube-fetch command. */
export async function bridgeReadsYouTube() {
  const [major = 0, minor = 0] = ((await bridgeVersion()) ?? '').split('.').map(Number);
  return major > 0 || minor >= 3;
}

type BridgeResponse = { status: number; contentType: string | null; body: string };

/** The caption provider's `fetch`, sent by Hibiki Bridge without the learner's YouTube cookies. */
export const bridgeFetch: typeof fetch = async (input, init) => {
  const signal = init?.signal;
  signal?.throwIfAborted();
  const request = bridgeRequest<BridgeResponse>(
    'youtube-fetch',
    {
      url: input instanceof Request ? input.url : String(input),
      method: init?.method ?? 'GET',
      headers: { 'Accept-Language': new Headers(init?.headers).get('Accept-Language') ?? 'ja' },
      body: typeof init?.body === 'string' ? init.body : undefined,
    },
    25000,
  );
  const result = await (signal
    ? Promise.race([
        request,
        new Promise<never>((_, reject) =>
          signal.addEventListener('abort', () => reject(signal.reason), { once: true }),
        ),
      ])
    : request);
  return new Response(result.body || null, {
    status: result.status,
    headers: result.contentType ? { 'Content-Type': result.contentType } : {},
  });
};

/** A practice lesson from the video's Japanese captions, read through Hibiki Bridge. */
export async function lessonFromBridgeCaptions(resolved: ResolvedMedia, signal: AbortSignal) {
  if (resolved.media.type !== 'youtube') throw new Error('Only YouTube captions can be read.');
  const { createDirectYoutubeCaptions } = await import('../providers/youtube-captions');
  const result = await createDirectYoutubeCaptions(bridgeFetch).transcribe(
    resolved.media.videoId,
    signal,
  );
  return createImportedLesson({
    resolved: {
      ...resolved,
      title: result.title || resolved.title,
      author: result.author || resolved.author,
    },
    cues: result.cues,
    transcriptType: 'provider-captions',
    provenance:
      BRIDGE_CAPTIONS + (autoGeneratedCaptions(result.provider) ? AUTO_GENERATED_SUFFIX : ''),
  });
}
